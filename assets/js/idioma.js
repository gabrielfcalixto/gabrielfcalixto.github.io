const idioma = (navigator.languages || [navigator.language])
    .map(tag => tag.toLowerCase().split("-")[0])
    .find(tag => ["pt", "en", "es"].includes(tag)) || "en";

function traduzir(texto) {
    return traducoes[texto.trim().replace(/\s+/g, " ")]?.[idioma] ?? texto;
}

function aplicarIdioma() {
    document.documentElement.lang = idioma === "pt" ? "pt-BR" : idioma;
    if (idioma === "pt") return;
    const textos = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    while (textos.nextNode()) {
        const no = textos.currentNode;
        if (no.textContent.trim()) no.textContent = traduzir(no.textContent);
    }
    document.querySelectorAll("[aria-label], img[alt]").forEach(elemento => {
        for (const atributo of ["aria-label", "alt"]) {
            if (elemento.hasAttribute(atributo)) {
                elemento.setAttribute(atributo, traduzir(elemento.getAttribute(atributo)));
            }
        }
    });
}
